"""Synthetic ENGRAM `knowledge.db` fixture builder for the Track-(b)
observation-arm harness tests.

**Freeze discipline (pre-reg §8 / task spec's "What NOT to do"): synthetic
data only.** Nothing in this module ever touches a real ENGRAM graph — every
row is hand-authored below.

**Schema-source decision (flagged as a judgment call).** The task spec
offered a choice: "either import and call the real schema-creation function
[from engram-alpha]... or copy the DDL verbatim into a constant with a
comment noting the source line, whichever is cleaner." This module copies
the DDL (vendors it), matching the SAME precedent
`tools/compression_fidelity/constants.py` already set for this repo
(vendor-with-a-pinned-comment, not a live cross-repo import) — engram-alpha
may not be checked out alongside engram-paper on every machine that runs
this test suite, and importing `engram_core` would also pull in that
module's full dependency surface (embeddings, config/path resolution, etc.)
just to reach one DDL string. `NODES_DDL`/`EDGES_DDL` below are copied
verbatim from `src/engram/engram_core.py`'s `_run_db_one_time_setup`
(base `CREATE TABLE nodes` ~lines 1334-1386; `CREATE TABLE edges`
~lines 1388-1395) with the `standpoint_author_id` / `fs_class` columns
(normally added via `ALTER TABLE ... ADD COLUMN` migrations, ~lines
1505-1532) folded directly into the base `CREATE TABLE` — a freshly-built
synthetic fixture DB has no migration history to replay, so folding those
columns into the initial `CREATE TABLE` is behaviorally identical to
create-then-migrate for our purposes.
"""

from __future__ import annotations

import json
import os
import sqlite3

NODES_DDL = """
CREATE TABLE IF NOT EXISTS nodes (
    id              TEXT PRIMARY KEY,
    type            TEXT NOT NULL,
    claim           TEXT,
    created_at      TEXT NOT NULL,

    -- Evidence-specific
    source_url      TEXT,
    source_title    TEXT,
    source_domain   TEXT,
    source_date     TEXT,
    source_accessed TEXT,
    content_snippet TEXT,

    -- Observation-specific
    evidence_id     TEXT REFERENCES nodes(id),
    quoted_text     TEXT,
    interpretation  TEXT,
    quote_type      TEXT,

    -- Prediction-specific
    predicted_event     TEXT,
    resolution_timeframe TEXT,
    status          TEXT DEFAULT 'active',
    resolved_by     TEXT REFERENCES nodes(id),

    -- Derivation/Theory-specific
    logical_chain   TEXT,

    -- Computed / versioning
    confidence          REAL,
    confidence_history  TEXT DEFAULT '[]',
    supersedes          TEXT REFERENCES nodes(id),
    superseded_by       TEXT REFERENCES nodes(id),
    is_current          INTEGER DEFAULT 1,
    metadata            TEXT DEFAULT '{}',

    -- Memory management (exponential forgetting)
    importance_base     REAL DEFAULT 0.5,
    importance_score    REAL DEFAULT 0.5,
    recall_turn         INTEGER DEFAULT 0,
    recall_count        INTEGER DEFAULT 0,
    memory_status       TEXT DEFAULT 'active',

    -- Utility scoring
    utility_score       REAL DEFAULT 0.0,

    -- Semantic embedding
    embedding           TEXT,

    -- standpoint / fs_class columns — ALTER-added in the real migration
    -- path (engram_core.py ~lines 1505-1532); folded into the base CREATE
    -- TABLE here (see module docstring).
    standpoint_author_id     TEXT,
    standpoint_collection_id TEXT,
    standpoint_override_tag  TEXT,
    standpoint_lineage       TEXT,
    standpoint_architecture  TEXT,
    fs_class                 TEXT
);
"""

EDGES_DDL = """
CREATE TABLE IF NOT EXISTS edges (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    source_id   TEXT NOT NULL REFERENCES nodes(id),
    target_id   TEXT NOT NULL REFERENCES nodes(id),
    relation    TEXT NOT NULL,
    created_at  TEXT NOT NULL,
    UNIQUE(source_id, target_id, relation)
);
"""

# Sensible defaults for any `nodes` column a fixture row dict doesn't
# specify. `id` is deliberately NOT defaulted — every row must name one
# explicitly (an autogenerated id would make fixture rows hard to reference
# from test assertions).
DEFAULT_COLUMNS: dict = {
    "type": "observation_factual",
    "claim": "synthetic claim",
    "created_at": "2026-01-01T00:00:00Z",
    "source_url": None,
    "source_title": None,
    "source_domain": None,
    "source_date": None,
    "source_accessed": None,
    "content_snippet": None,
    "evidence_id": None,
    "quoted_text": "synthetic quoted text",
    "interpretation": None,
    "quote_type": "attributed_analysis",
    "predicted_event": None,
    "resolution_timeframe": None,
    "status": "active",
    "resolved_by": None,
    "logical_chain": None,
    "confidence": 0.7,
    "confidence_history": "[]",
    "supersedes": None,
    "superseded_by": None,
    "is_current": 1,
    "metadata": "{}",
    "importance_base": 0.5,
    "importance_score": 0.5,
    "recall_turn": 0,
    "recall_count": 0,
    "memory_status": "active",
    "utility_score": 0.0,
    "embedding": None,
    "standpoint_author_id": None,
    "standpoint_collection_id": None,
    "standpoint_override_tag": None,
    "standpoint_lineage": None,
    "standpoint_architecture": None,
    "fs_class": None,
}


def _insert_node_row(conn: sqlite3.Connection, row: dict) -> None:
    if "id" not in row:
        raise ValueError("Each fixture node row dict must specify an explicit 'id'.")
    merged = dict(DEFAULT_COLUMNS)
    merged.update(row)
    if isinstance(merged.get("metadata"), dict):
        merged["metadata"] = json.dumps(merged["metadata"])
    columns = list(merged.keys())
    placeholders = ",".join("?" for _ in columns)
    col_list = ",".join(columns)
    conn.execute(
        f"INSERT INTO nodes ({col_list}) VALUES ({placeholders})",
        [merged[c] for c in columns],
    )


def _insert_edge(conn: sqlite3.Connection, edge: dict) -> None:
    conn.execute(
        "INSERT INTO edges (source_id, target_id, relation, created_at) VALUES (?, ?, ?, ?)",
        (
            edge["source_id"],
            edge["target_id"],
            edge["relation"],
            edge.get("created_at", "2026-01-01T00:00:00Z"),
        ),
    )


def build_synthetic_db(tmp_path, rows: list[dict]) -> str:
    """Create a synthetic knowledge.db (real `nodes`/`edges` schema, see
    `NODES_DDL`/`EDGES_DDL`) at `tmp_path` (or `tmp_path/synthetic.db` if
    `tmp_path` doesn't already name a `.db` file) and insert `rows`. Returns
    the db file path (str).

    `rows` is a list of dicts, in one of two shapes:

      - a NODE row: any dict of `nodes`-table column -> value (must include
        `'id'`; unspecified columns fall back to `DEFAULT_COLUMNS`).
      - an EDGE row: `{"_edge": {"source_id": ..., "target_id": ...,
        "relation": ..., "created_at": <optional>}}`.

    **The `{"_edge": ...}` reserved-key convention is a judgment call, not
    part of the coder-fairy spec's literal `rows: list[dict]` signature**
    (which described node rows). The contradicted-and-lost + derived-from-
    lineage fixtures (see `default_fixture_rows`) need `contradicts` /
    `resolves` / `derives_from` / `supported_by` edges wired between
    synthetic nodes, and the pinned function signature has no separate
    `edges` parameter — so this module adds a minimal reserved-key
    convention rather than changing the signature. Flagged for review; a
    cleaner alternative would be an explicit `edges: list[dict] | None =
    None` parameter if the parent prefers that over a sentinel dict shape.
    """
    db_path = str(tmp_path)
    if not db_path.endswith(".db"):
        db_path = os.path.join(db_path, "synthetic.db")

    conn = sqlite3.connect(db_path)
    try:
        conn.executescript(NODES_DDL + EDGES_DDL)
        for row in rows:
            if "_edge" in row:
                _insert_edge(conn, row["_edge"])
            else:
                _insert_node_row(conn, row)
        conn.commit()
    finally:
        conn.close()
    return db_path


# ---------------------------------------------------------------------------
# Fixture SET — covers every outcome-classification branch, at minimum once
# each, plus the fs_class proxy-fallback / native-override pair.
#
# ID naming convention: `ob_fx_<branch>` for observation nodes, `ct_fx_<n>`
# for contradiction nodes, `dv_fx_<n>` for the one synthetic derivation node
# needed as a "wins-by-derivation" resolver, `ev_fx_<n>` for evidence nodes.
# ---------------------------------------------------------------------------


def default_fixture_rows() -> list[dict]:
    """The primary fixture set ("graph A" in the multi-graph merge test) —
    covers every `classify_outcome` branch at least once, plus the
    `fs_class` proxy-fallback (`ob_fx_survived_plain`, `fs_class=None`,
    `quote_type='hard_data'` -> proxy `'re-executable'`) vs. native-override
    (`ob_fx_survived_fsclass_override`, `fs_class='re-executable'` set
    directly despite `quote_type='editorial'`, whose proxy would otherwise
    say `'frozen'` -> the native field must win) pair.

    Also includes `ob_0001` (a plain survived node) under an id that
    deliberately COLLIDES with `secondary_graph_fixture_rows()`'s sole node
    — exercising fetch_frame_multi's id-collision-safe merging (same `id`,
    different `graph_id`, both preserved as distinct `NodeRow`s).
    """
    rows: list[dict] = []

    # ---- evidence node (shared source_domain/source_date for several obs)
    rows.append({
        "id": "ev_fx_0001",
        "type": "evidence",
        "claim": None,
        "source_url": "https://example.com/article",
        "source_domain": "example.com",
        "source_date": "2026-01-01",
        "quoted_text": None,
    })

    # ---- refuted: one per INCLUDE error_type ------------------------------
    for suffix, error_type in (
        ("hallucinated", "hallucinated_claim"),
        ("wrong_evidence", "wrong_evidence"),
        ("fabricated", "fabricated_quote"),
        ("other", "other"),
    ):
        rows.append({
            "id": f"ob_fx_refuted_{suffix}",
            "type": "observation_factual",
            "claim": f"A refuted claim ({suffix}).",
            "evidence_id": "ev_fx_0001",
            "quoted_text": "some quoted text",
            "quote_type": "attributed_analysis",
            "status": "retracted",
            "is_current": 0,
            "metadata": {"error_type": error_type, "retracted": True},
        })

    # ---- excluded: duplicate, wrong_citation ------------------------------
    for suffix, error_type in (
        ("duplicate", "duplicate"),
        ("wrong_citation", "wrong_citation"),
    ):
        rows.append({
            "id": f"ob_fx_excluded_{suffix}",
            "type": "observation_factual",
            "claim": f"An excluded claim ({suffix}).",
            "evidence_id": "ev_fx_0001",
            "status": "retracted",
            "is_current": 0,
            "metadata": {"error_type": error_type, "retracted": True},
        })

    # ---- contradicted-and-lost: clean case (resolver IS the winning side) -
    # ct_fx_0001: A (loser) vs B (winner); B itself resolves the dispute.
    rows.append({"id": "ob_fx_contra_loser_a", "type": "observation_factual",
                 "claim": "Side A of a resolved contradiction."})
    rows.append({"id": "ob_fx_contra_winner_b", "type": "observation_factual",
                 "claim": "Side B of a resolved contradiction (wins by being the resolver)."})
    rows.append({
        "id": "ct_fx_0001", "type": "contradiction",
        "claim": "A vs B contradiction, resolved.",
        "status": "resolved", "resolved_by": "ob_fx_contra_winner_b",
    })
    rows.append({"_edge": {"source_id": "ct_fx_0001", "target_id": "ob_fx_contra_loser_a", "relation": "contradicts"}})
    rows.append({"_edge": {"source_id": "ct_fx_0001", "target_id": "ob_fx_contra_winner_b", "relation": "contradicts"}})
    rows.append({"_edge": {"source_id": "ob_fx_contra_winner_b", "target_id": "ct_fx_0001", "relation": "resolves"}})

    # ---- contradicted-and-lost: derived-from case (resolver is a separate
    # derivation that derives_from the winning side) -----------------------
    # ct_fx_0002: J (loser) vs K (winner); dv_fx_0001 derives_from K and
    # resolves ct_fx_0002.
    rows.append({"id": "ob_fx_contra_loser_j", "type": "observation_factual",
                 "claim": "Side J, loses via derived-from resolution."})
    rows.append({"id": "ob_fx_contra_winner_k", "type": "observation_factual",
                 "claim": "Side K, wins via derived-from resolution."})
    rows.append({"id": "dv_fx_0001", "type": "derivation",
                 "claim": "A derivation citing K as its premise, resolving the J-vs-K dispute."})
    rows.append({
        "id": "ct_fx_0002", "type": "contradiction",
        "claim": "J vs K contradiction, resolved via a citing derivation.",
        "status": "resolved", "resolved_by": "dv_fx_0001",
    })
    rows.append({"_edge": {"source_id": "ct_fx_0002", "target_id": "ob_fx_contra_loser_j", "relation": "contradicts"}})
    rows.append({"_edge": {"source_id": "ct_fx_0002", "target_id": "ob_fx_contra_winner_k", "relation": "contradicts"}})
    rows.append({"_edge": {"source_id": "dv_fx_0001", "target_id": "ob_fx_contra_winner_k", "relation": "derives_from"}})
    rows.append({"_edge": {"source_id": "dv_fx_0001", "target_id": "ct_fx_0002", "relation": "resolves"}})

    # ---- contradicted-and-lost: AMBIGUOUS case (resolver is structurally
    # independent of both disputed sides) -- the exact piece flagged for
    # close review in db.py's `_contradicted_and_lost` docstring. ----------
    rows.append({"id": "ob_fx_contra_ambig_e", "type": "observation_factual",
                 "claim": "Side E of an ambiguously-resolved contradiction."})
    rows.append({"id": "ob_fx_contra_ambig_f", "type": "observation_factual",
                 "claim": "Side F of an ambiguously-resolved contradiction."})
    rows.append({"id": "ob_fx_contra_ambig_resolver_g", "type": "observation_factual",
                 "claim": "An independent node that resolves E-vs-F without deriving from either."})
    rows.append({
        "id": "ct_fx_0003", "type": "contradiction",
        "claim": "E vs F contradiction, resolved by an unrelated node.",
        "status": "resolved", "resolved_by": "ob_fx_contra_ambig_resolver_g",
    })
    rows.append({"_edge": {"source_id": "ct_fx_0003", "target_id": "ob_fx_contra_ambig_e", "relation": "contradicts"}})
    rows.append({"_edge": {"source_id": "ct_fx_0003", "target_id": "ob_fx_contra_ambig_f", "relation": "contradicts"}})
    rows.append({"_edge": {"source_id": "ob_fx_contra_ambig_resolver_g", "target_id": "ct_fx_0003", "relation": "resolves"}})

    # ---- superseded / unclassified -----------------------------------------
    rows.append({"id": "ob_fx_superseded_successor", "type": "observation_factual",
                 "claim": "The current successor of a superseded node."})
    rows.append({
        "id": "ob_fx_superseded", "type": "observation_factual",
        "claim": "A superseded (not retracted) node -- deliberately unclassified.",
        "is_current": 0, "superseded_by": "ob_fx_superseded_successor",
    })

    # ---- survived: plain active node, fs_class NULL -> proxy fallback -----
    rows.append({
        "id": "ob_fx_survived_plain", "type": "observation_factual",
        "claim": "A plain survived observation.",
        "evidence_id": "ev_fx_0001", "quote_type": "hard_data", "fs_class": None,
    })

    # ---- survived: fs_class explicitly set, native field wins over proxy --
    rows.append({
        "id": "ob_fx_survived_fsclass_override", "type": "observation_factual",
        "claim": "A survived observation whose native fs_class overrides the quote_type proxy.",
        "quote_type": "editorial", "fs_class": "re-executable",
    })

    # ---- observation_predictive: confirm the second observation type is
    # also scoped into the frame. --------------------------------------
    rows.append({
        "id": "ob_fx_survived_predictive", "type": "observation_predictive",
        "claim": "A survived predictive observation.",
    })

    # ---- id-collision fixture (see docstring) ------------------------------
    rows.append({
        "id": "ob_0001", "type": "observation_factual",
        "claim": "Graph-A's version of ob_0001.",
    })

    return rows


def secondary_graph_fixture_rows() -> list[dict]:
    """A second, minimal fixture set ("graph B" in the multi-graph merge
    test) — deliberately reuses the id `ob_0001` (with a DIFFERENT claim)
    to test that `fetch_frame_multi` disambiguates same-id nodes across
    different graphs via `graph_id`, rather than silently colliding/
    deduplicating them.
    """
    return [
        {"id": "ob_0001", "type": "observation_factual",
         "claim": "Graph-B's version of ob_0001."},
        {"id": "ob_fx_graph_b_only", "type": "observation_factual",
         "claim": "A node that exists only in graph B."},
    ]
